"""
=========================================================
PyTorch Seismic Dataset
=========================================================

Loads synthetic seismic cubes generated by the
DatasetGenerator.

Each sample consists of

• Ground Truth Cube
• Corrupted Cube
• Binary Sampling Mask

These samples are returned as PyTorch tensors for
training the Physics-Informed 3D Encoder–Decoder
Framework.

Author: Ormin Joseph
=========================================================
"""

import os

import numpy as np

import torch

from torch.utils.data import Dataset

class SeismicDataset(Dataset):

    """
    PyTorch Dataset for synthetic seismic cubes.

    Each dataset sample contains

    • Ground Truth
    • Corrupted Cube
    • Binary Mask
    """

    def __init__(
            self,
            dataset_directory="datasets"
    ):
        """
        Initialize dataset.

        Parameters
        ----------
        dataset_directory : str
            Folder containing the generated .npy files.
        """

        self.dataset_directory = dataset_directory
        # ------------------------------------------
        # Locate ground-truth files
        # ------------------------------------------

        self.ground_truth_files = sorted(

            [

                file

                for file in os.listdir(

                self.dataset_directory

            )

                if file.endswith("_gt.npy")

            ]

        )

    # --------------------------------------------------
    # Dataset Length
    # --------------------------------------------------

    def __len__(self):
        """
        Return the number of samples in the dataset.
        """

        return len(
            self.ground_truth_files
        )

    # --------------------------------------------------
    # Load One Sample
    # --------------------------------------------------

    def __getitem__(
            self,
            index
    ):
        """
        Load one seismic training sample.

        Parameters
        ----------
        index : int
        Dataset sample index.
        """
        # ------------------------------------------
        # Ground-truth filename
        # ------------------------------------------

        ground_truth_file = (
            self.ground_truth_files[index]
        )

        # ------------------------------------------
        # Corresponding filenames
        # ------------------------------------------

        corrupted_file = (

            ground_truth_file.replace(
                "_gt.npy",

                "_corrupted.npy"
            )
        )

        mask_file = (

            ground_truth_file.replace(

                "_gt.npy",

                "_mask.npy"
            )
        )
        # ------------------------------------------
        # Load NumPy arrays
        # ------------------------------------------

        ground_truth = np.load(

            os.path.join(

                self.dataset_directory,

                ground_truth_file
            )
        )

        corrupted = np.load(

            os.path.join(

                self.dataset_directory,

                corrupted_file
            )
        )

        mask = np.load(

            os.path.join(

                self.dataset_directory,

                mask_file
            )
        )
        # ------------------------------------------
        # Convert to PyTorch tensors
        # ------------------------------------------

        ground_truth = torch.from_numpy(

            ground_truth

        ).float()

        corrupted = torch.from_numpy(

            corrupted

        ).float()

        mask = torch.from_numpy(

            mask

        ).float()

        # ------------------------------------------
        # Return sample
        # ------------------------------------------

        return (

            ground_truth,

            corrupted,

            mask
        )


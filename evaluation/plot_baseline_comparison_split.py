"""
=========================================================
Baseline Metrics Plot
=========================================================

Creates separate publication-quality plots for:

    1. Reconstruction error metrics
       - MAE
       - RMSE

    2. Reconstruction quality metrics
       - PSNR
       - SNR
       - SSIM

The script reads the results generated by:

    evaluation/compare_with_baselines.py

The input/output directory is obtained from config.py
through REPORT_DIR.

Author: Ormin Joseph
=========================================================
"""

import os

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from utils.config import REPORT_DIR


# =========================================================
# FILE PATHS
# =========================================================

CSV_FILE = os.path.join(
    REPORT_DIR,
    "baseline_comparison.csv"
)

ERROR_OUTPUT_FILE = os.path.join(
    REPORT_DIR,
    "baseline_error_metrics.png"
)

QUALITY_OUTPUT_FILE = os.path.join(
    REPORT_DIR,
    "baseline_quality_metrics.png"
)


# =========================================================
# REQUIRED COLUMNS
# =========================================================

REQUIRED_COLUMNS = [
    "Method",
    "MAE",
    "RMSE",
    "PSNR",
    "SNR",
    "SSIM"
]


# =========================================================
# LOAD AND VALIDATE RESULTS
# =========================================================

def load_results(csv_file):
    """
    Load and validate the baseline comparison results.
    """

    # -----------------------------------------------------
    # Check that the CSV file exists
    # -----------------------------------------------------

    if not os.path.exists(csv_file):
        raise FileNotFoundError(
            f"\nBaseline comparison file not found:\n"
            f"{csv_file}\n\n"
            "Run evaluation/compare_with_baselines.py "
            "before running this plotting script."
        )

    # -----------------------------------------------------
    # Read CSV
    # -----------------------------------------------------

    df = pd.read_csv(csv_file)

    # -----------------------------------------------------
    # Check for empty file
    # -----------------------------------------------------

    if df.empty:
        raise ValueError(
            f"\nBaseline comparison file is empty:\n"
            f"{csv_file}"
        )

    # -----------------------------------------------------
    # Check required columns
    # -----------------------------------------------------

    missing_columns = [
        column
        for column in REQUIRED_COLUMNS
        if column not in df.columns
    ]

    if missing_columns:
        raise ValueError(
            "\nMissing required columns in "
            "baseline_comparison.csv:\n"
            f"{missing_columns}"
        )

    # -----------------------------------------------------
    # Validate method names
    # -----------------------------------------------------

    if df["Method"].isna().any():
        raise ValueError(
            "\nThe 'Method' column contains missing values."
        )

    # -----------------------------------------------------
    # Validate numerical metrics
    # -----------------------------------------------------

    metrics = [
        "MAE",
        "RMSE",
        "PSNR",
        "SNR",
        "SSIM"
    ]

    for metric in metrics:

        df[metric] = pd.to_numeric(
            df[metric],
            errors="coerce"
        )

        if df[metric].isna().any():
            raise ValueError(
                f"\nMetric '{metric}' contains "
                "missing or non-numeric values."
            )

        if not np.isfinite(
            df[metric].to_numpy()
        ).all():
            raise ValueError(
                f"\nMetric '{metric}' contains "
                "non-finite values."
            )

    return df


# =========================================================
# ERROR METRICS PLOT
# =========================================================

def plot_error_metrics(df, output_file):
    """
    Plot MAE and RMSE for all reconstruction methods.
    """

    methods = df["Method"].astype(str).tolist()

    x = np.arange(len(methods))

    width = 0.35

    fig, ax = plt.subplots(
        figsize=(9, 6)
    )

    # -----------------------------------------------------
    # MAE
    # -----------------------------------------------------

    ax.bar(
        x - width / 2,
        df["MAE"],
        width=width,
        label="MAE"
    )

    # -----------------------------------------------------
    # RMSE
    # -----------------------------------------------------

    ax.bar(
        x + width / 2,
        df["RMSE"],
        width=width,
        label="RMSE"
    )

    # -----------------------------------------------------
    # X-axis
    # -----------------------------------------------------

    ax.set_xticks(x)

    ax.set_xticklabels(
        methods,
        rotation=15,
        ha="right"
    )

    # -----------------------------------------------------
    # Labels
    # -----------------------------------------------------

    ax.set_xlabel(
        "Reconstruction Method"
    )

    ax.set_ylabel(
        "Error"
    )

    ax.set_title(
        "Baseline Comparison: Reconstruction Error Metrics"
    )

    # -----------------------------------------------------
    # Grid
    # -----------------------------------------------------

    ax.grid(
        axis="y",
        linestyle="--",
        alpha=0.3
    )

    # -----------------------------------------------------
    # Legend
    # -----------------------------------------------------

    ax.legend()

    # -----------------------------------------------------
    # Layout
    # -----------------------------------------------------

    fig.tight_layout()

    # -----------------------------------------------------
    # Ensure directory exists
    # -----------------------------------------------------

    os.makedirs(
        os.path.dirname(output_file),
        exist_ok=True
    )

    # -----------------------------------------------------
    # Save figure
    # -----------------------------------------------------

    fig.savefig(
        output_file,
        dpi=300,
        bbox_inches="tight"
    )

    plt.close(fig)


# =========================================================
# QUALITY METRICS PLOT
# =========================================================

def plot_quality_metrics(df, output_file):
    """
    Plot PSNR, SNR and SSIM for all reconstruction methods.

    Note:
        These metrics have different numerical scales.
        Therefore, this figure is useful for visual comparison,
        but the exact numerical values should also be reported
        in the CSV/table.
    """

    methods = df["Method"].astype(str).tolist()

    x = np.arange(len(methods))

    width = 0.25

    fig, ax = plt.subplots(
        figsize=(10, 6)
    )

    # -----------------------------------------------------
    # PSNR
    # -----------------------------------------------------

    ax.bar(
        x - width,
        df["PSNR"],
        width=width,
        label="PSNR"
    )

    # -----------------------------------------------------
    # SNR
    # -----------------------------------------------------

    ax.bar(
        x,
        df["SNR"],
        width=width,
        label="SNR"
    )

    # -----------------------------------------------------
    # SSIM
    # -----------------------------------------------------

    ax.bar(
        x + width,
        df["SSIM"],
        width=width,
        label="SSIM"
    )

    # -----------------------------------------------------
    # X-axis
    # -----------------------------------------------------

    ax.set_xticks(x)

    ax.set_xticklabels(
        methods,
        rotation=15,
        ha="right"
    )

    # -----------------------------------------------------
    # Labels
    # -----------------------------------------------------

    ax.set_xlabel(
        "Reconstruction Method"
    )

    ax.set_ylabel(
        "Metric Value"
    )

    ax.set_title(
        "Baseline Comparison: Reconstruction Quality Metrics"
    )

    # -----------------------------------------------------
    # Grid
    # -----------------------------------------------------

    ax.grid(
        axis="y",
        linestyle="--",
        alpha=0.3
    )

    # -----------------------------------------------------
    # Legend
    # -----------------------------------------------------

    ax.legend()

    # -----------------------------------------------------
    # Layout
    # -----------------------------------------------------

    fig.tight_layout()

    # -----------------------------------------------------
    # Ensure directory exists
    # -----------------------------------------------------

    os.makedirs(
        os.path.dirname(output_file),
        exist_ok=True
    )

    # -----------------------------------------------------
    # Save figure
    # -----------------------------------------------------

    fig.savefig(
        output_file,
        dpi=300,
        bbox_inches="tight"
    )

    plt.close(fig)


# =========================================================
# MAIN
# =========================================================

def main():

    print()
    print("=" * 60)
    print("BASELINE METRICS PLOT")
    print("=" * 60)

    print()
    print("Input file:")
    print(CSV_FILE)

    # -----------------------------------------------------
    # Load results
    # -----------------------------------------------------

    df = load_results(
        CSV_FILE
    )

    print()
    print("Methods found:")

    for method in df["Method"]:
        print(f"  - {method}")

    # -----------------------------------------------------
    # Create error metrics plot
    # -----------------------------------------------------

    print()
    print("Creating error metrics plot...")

    plot_error_metrics(
        df,
        ERROR_OUTPUT_FILE
    )

    print(
        f"Saved:\n{ERROR_OUTPUT_FILE}"
    )

    # -----------------------------------------------------
    # Create quality metrics plot
    # -----------------------------------------------------

    print()
    print("Creating quality metrics plot...")

    plot_quality_metrics(
        df,
        QUALITY_OUTPUT_FILE
    )

    print(
        f"Saved:\n{QUALITY_OUTPUT_FILE}"
    )

    # -----------------------------------------------------
    # Completion message
    # -----------------------------------------------------

    print()
    print("=" * 60)
    print("BASELINE METRICS PLOT COMPLETE")
    print("=" * 60)


# =========================================================
# ENTRY POINT
# =========================================================

if __name__ == "__main__":
    main()
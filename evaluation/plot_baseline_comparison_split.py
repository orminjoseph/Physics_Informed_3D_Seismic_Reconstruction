import os

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from utils.config import REPORT_DIR


# =========================================================
# FILE PATHS
# =========================================================

# Input CSV generated by the baseline comparison module.
CSV_FILE = os.path.join(
    REPORT_DIR,
    "baseline_comparison.csv",
)

# Output figure containing MAE and RMSE.
ERROR_OUTPUT_FILE = os.path.join(
    REPORT_DIR,
    "baseline_error_metrics.png",
)

# Output figure containing PSNR, SNR and SSIM.
QUALITY_OUTPUT_FILE = os.path.join(
    REPORT_DIR,
    "baseline_quality_metrics.png",
)


# =========================================================
# EXPECTED METHODS
# =========================================================

EXPECTED_METHODS = [
    "Nearest Neighbor",
    "Linear Interpolation",
    "f-x Prediction",
    "Compressive Sensing",
    "Curvelet POCS",
    "Dictionary Learning",
    "Proposed Physics-Informed 3D Encoder–Decoder",
]


# =========================================================
# REQUIRED COLUMNS
# =========================================================

REQUIRED_COLUMNS = [
    "Method",
    "MAE",
    "RMSE",
    "PSNR",
    "SNR",
    "SSIM",
]


# =========================================================
# METRIC DEFINITIONS
# =========================================================

ERROR_METRICS = [
    "MAE",
    "RMSE",
]

QUALITY_METRICS = [
    "PSNR",
    "SNR",
    "SSIM",
]


# =========================================================
# LOAD AND VALIDATE RESULTS
# =========================================================

def load_results(csv_file):
    """
    Load and validate the baseline comparison results.

    Parameters
    ----------
    csv_file : str
        Path to baseline_comparison.csv.

    Returns
    -------
    pandas.DataFrame
        Validated baseline comparison results.
    """

    # -----------------------------------------------------
    # Check input file
    # -----------------------------------------------------

    if not os.path.exists(csv_file):

        raise FileNotFoundError(
            "\nBaseline comparison file not found:\n"
            f"{csv_file}\n\n"
            "Run "
            "evaluation/baselines/"
            "compare_with_baselines.py "
            "before running this plotting script."
        )

    # -----------------------------------------------------
    # Read CSV
    # -----------------------------------------------------

    df = pd.read_csv(
        csv_file
    )

    # -----------------------------------------------------
    # Check for empty file
    # -----------------------------------------------------

    if df.empty:

        raise ValueError(
            "\nBaseline comparison file is empty:\n"
            f"{csv_file}"
        )

    # -----------------------------------------------------
    # Check required columns
    # -----------------------------------------------------

    missing_columns = [
        column
        for column in REQUIRED_COLUMNS
        if column not in df.columns
    ]

    if missing_columns:

        raise ValueError(
            "\nMissing required columns in "
            "baseline_comparison.csv:\n"
            f"{missing_columns}"
        )

    # -----------------------------------------------------
    # Validate Method column
    # -----------------------------------------------------

    if df["Method"].isna().any():

        raise ValueError(
            "\nThe 'Method' column contains "
            "missing values."
        )

    # Convert method names to strings and remove
    # accidental leading/trailing whitespace.
    df["Method"] = (
        df["Method"]
        .astype(str)
        .str.strip()
    )

    # Check for empty method names.
    if (df["Method"] == "").any():

        raise ValueError(
            "\nThe 'Method' column contains "
            "empty method names."
        )

    # -----------------------------------------------------
    # Check for duplicate methods
    # -----------------------------------------------------

    duplicate_methods = (
        df["Method"][
            df["Method"].duplicated(
                keep=False
            )
        ]
        .unique()
        .tolist()
    )

    if duplicate_methods:

        raise ValueError(
            "\nDuplicate reconstruction methods "
            "were found:\n"
            f"{duplicate_methods}\n\n"
            "The common baseline comparison must "
            "contain one result row per method."
        )

    # -----------------------------------------------------
    # Validate expected seven-method comparison
    # -----------------------------------------------------

    found_methods = set(
        df["Method"].tolist()
    )

    expected_methods = set(
        EXPECTED_METHODS
    )

    missing_methods = (
        expected_methods
        -
        found_methods
    )

    unexpected_methods = (
        found_methods
        -
        expected_methods
    )

    if missing_methods:

        raise ValueError(
            "\nExpected baseline method(s) "
            "are missing:\n"
            f"{sorted(missing_methods)}"
        )

    if unexpected_methods:

        raise ValueError(
            "\nUnexpected method name(s) found:\n"
            f"{sorted(unexpected_methods)}\n\n"
            "Check that the producer script and "
            "plotting script use the same method names."
        )

    # -----------------------------------------------------
    # Ensure exactly seven methods are present
    # -----------------------------------------------------

    if len(df) != len(
        EXPECTED_METHODS
    ):

        raise ValueError(
            "\nThe baseline comparison must contain "
            f"exactly {len(EXPECTED_METHODS)} methods. "
            f"Found {len(df)} rows."
        )

    # -----------------------------------------------------
    # Validate numerical metrics
    # -----------------------------------------------------

    for metric in (
        ERROR_METRICS
        +
        QUALITY_METRICS
    ):

        # Convert values to numeric.
        df[metric] = pd.to_numeric(
            df[metric],
            errors="coerce",
        )

        # Check missing/non-numeric values.
        if df[metric].isna().any():

            raise ValueError(
                f"\nMetric '{metric}' contains "
                "missing or non-numeric values."
            )

        # Check finite values.
        if not np.isfinite(
            df[metric].to_numpy()
        ).all():

            raise ValueError(
                f"\nMetric '{metric}' contains "
                "non-finite values."
            )

    # -----------------------------------------------------
    # Validate SSIM range
    # -----------------------------------------------------
    #
    # SSIM is normally bounded within [-1, 1].
    # The reconstruction framework should produce
    # physically meaningful SSIM values within this range.
    # -----------------------------------------------------

    if (
        (df["SSIM"] < -1.0)
        |
        (df["SSIM"] > 1.0)
    ).any():

        raise ValueError(
            "\nSSIM contains values outside the "
            "expected range [-1, 1]."
        )

    # -----------------------------------------------------
    # Validate metric consistency
    # -----------------------------------------------------

    # MAE and RMSE should not be negative.
    for metric in [
        "MAE",
        "RMSE",
    ]:

        if (
            df[metric] < 0
        ).any():

            raise ValueError(
                f"\nMetric '{metric}' contains "
                "negative values."
            )

    # -----------------------------------------------------
    # Reorder rows according to the controlled
    # seven-method comparison order.
    #
    # This is an organizational order only.
    # It is NOT a performance ranking.
    # -----------------------------------------------------

    method_order = pd.Categorical(
        df["Method"],
        categories=EXPECTED_METHODS,
        ordered=True,
    )

    df = (
        df.assign(
            _method_order=method_order
        )
        .sort_values(
            "_method_order"
        )
        .drop(
            columns="_method_order"
        )
        .reset_index(
            drop=True
        )
    )

    return df


# =========================================================
# COMMON FIGURE SETTINGS
# =========================================================

def configure_axis(
    ax,
    title,
    ylabel,
):
    """
    Apply common publication-style axis settings.

    Parameters
    ----------
    ax : matplotlib.axes.Axes
        Target axis.

    title : str
        Plot title.

    ylabel : str
        Y-axis label.
    """

    ax.set_title(
        title,
        fontsize=12,
        fontweight="bold",
    )

    ax.set_xlabel(
        "Reconstruction Method",
        fontsize=10,
    )

    ax.set_ylabel(
        ylabel,
        fontsize=10,
    )

    ax.tick_params(
        axis="x",
        labelrotation=25,
    )

    ax.grid(
        axis="y",
        linestyle="--",
        alpha=0.30,
    )

    # Place grid behind bars.
    ax.set_axisbelow(
        True
    )


# =========================================================
# ERROR METRICS PLOT
# =========================================================

def plot_error_metrics(
    df,
    output_file,
):
    """
    Plot MAE and RMSE.

    Both metrics are error measures and are therefore
    presented together in a two-panel figure.

    Parameters
    ----------
    df : pandas.DataFrame
        Validated baseline results.

    output_file : str
        Output figure path.
    """

    methods = (
        df["Method"]
        .astype(str)
        .tolist()
    )

    x = np.arange(
        len(methods)
    )

    # -----------------------------------------------------
    # Create figure
    # -----------------------------------------------------

    fig, axes = plt.subplots(
        2,
        1,
        figsize=(11, 10),
    )

    # -----------------------------------------------------
    # MAE
    # -----------------------------------------------------

    axes[0].bar(
        x,
        df["MAE"].to_numpy(),
    )

    configure_axis(
        axes[0],
        "Mean Absolute Error (MAE)",
        "MAE",
    )

    axes[0].set_xticks(
        x
    )

    axes[0].set_xticklabels(
        methods,
        rotation=25,
        ha="right",
    )

    # -----------------------------------------------------
    # RMSE
    # -----------------------------------------------------

    axes[1].bar(
        x,
        df["RMSE"].to_numpy(),
    )

    configure_axis(
        axes[1],
        "Root Mean Square Error (RMSE)",
        "RMSE",
    )

    axes[1].set_xticks(
        x
    )

    axes[1].set_xticklabels(
        methods,
        rotation=25,
        ha="right",
    )

    # -----------------------------------------------------
    # Overall figure title
    # -----------------------------------------------------

    fig.suptitle(
        "Baseline Comparison: Reconstruction Error Metrics",
        fontsize=14,
        fontweight="bold",
        y=0.995,
    )

    # -----------------------------------------------------
    # Layout
    # -----------------------------------------------------

    fig.tight_layout(
        rect=[
            0,
            0,
            1,
            0.97,
        ]
    )

    # -----------------------------------------------------
    # Ensure output directory exists
    # -----------------------------------------------------

    output_directory = os.path.dirname(
        output_file
    )

    if output_directory:

        os.makedirs(
            output_directory,
            exist_ok=True,
        )

    # -----------------------------------------------------
    # Save figure
    # -----------------------------------------------------

    fig.savefig(
        output_file,
        dpi=300,
        bbox_inches="tight",
    )

    plt.close(
        fig
    )



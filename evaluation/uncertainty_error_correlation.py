# 2. ANALYSIS CONFIGURATION
# =====================================================================

# Numerical threshold used when determining whether an array has
# effectively zero variance.
VARIANCE_EPSILON = 1.0e-12

# Minimum number of paired observations required for correlation.
MIN_CORRELATION_SAMPLES = 3


# =====================================================================
# 3. REPRODUCIBILITY
# =====================================================================

def set_random_seed(seed):
    """
    Set random seeds for reproducible analysis.
    """

    random.seed(seed)

    np.random.seed(seed)

    torch.manual_seed(seed)

    if torch.cuda.is_available():

        torch.cuda.manual_seed_all(seed)


# =====================================================================
# 4. ARRAY VALIDATION
# =====================================================================

def validate_array(
    array,
    name,
):
    """
    Convert an input array to float64 NumPy format and validate it.

    Parameters
    ----------
    array : array-like
        Input numerical data.

    name : str
        Descriptive name used in error messages.

    Returns
    -------
    numpy.ndarray
        Validated one-dimensional array.
    """

    array = np.asarray(
        array,
        dtype=np.float64,
    )

    # Flatten the array so every element represents one observation.
    array = array.reshape(-1)

    # Reject empty arrays.
    if array.size == 0:

        raise ValueError(
            f"{name} is empty."
        )

    # Reject invalid numerical values.
    if not np.all(
        np.isfinite(array)
    ):

        raise ValueError(
            f"{name} contains NaN or infinite values."
        )

    return array


# =====================================================================
# 5. CORRELATION FUNCTION
# =====================================================================

def calculate_correlations(
    uncertainty,
    error,
):
    """
    Calculate Pearson and Spearman correlations.

    Parameters
    ----------
    uncertainty : numpy.ndarray
        Uncertainty values.

    error : numpy.ndarray
        Absolute reconstruction-error values.

    Returns
    -------
    tuple
        Pearson correlation, Pearson p-value,
        Spearman correlation, Spearman p-value.
    """

    uncertainty = validate_array(
        uncertainty,
        "Uncertainty",
    )

    error = validate_array(
        error,
        "Reconstruction error",
    )

    # Verify equal observation counts.
    if uncertainty.size != error.size:

        raise ValueError(
            "Uncertainty and reconstruction error contain "
            "different numbers of observations."
        )

    # Require enough observations.
    if uncertainty.size < MIN_CORRELATION_SAMPLES:

        return (
            np.nan,
            np.nan,
            np.nan,
            np.nan,
        )

    # Correlation is undefined when either variable is effectively
    # constant.
    if (
        np.std(uncertainty) < VARIANCE_EPSILON
        or
        np.std(error) < VARIANCE_EPSILON
    ):

        return (
            np.nan,
            np.nan,
            np.nan,
            np.nan,
        )

    # Pearson correlation.
    pearson_result = pearsonr(
        error,
        uncertainty,
    )

    pearson_corr = float(
        pearson_result.statistic
    )

    pearson_p = float(
        pearson_result.pvalue
    )

    # Spearman correlation.
    spearman_result = spearmanr(
        error,
        uncertainty,
    )

    spearman_corr = float(
        spearman_result.statistic
    )

    spearman_p = float(
        spearman_result.pvalue
    )

    return (
        pearson_corr,
        pearson_p,
        spearman_corr,
        spearman_p,
    )


# =====================================================================
# 6. SAFE CORRELATION RESULT
# =====================================================================

def correlation_record(
    uncertainty_name,
    uncertainty,
    error,
    patch_index=None,
):
    """
    Create a standardized correlation result record.
    """

    (
        pearson_corr,
        pearson_p,
        spearman_corr,
        spearman_p,
    ) = calculate_correlations(
        uncertainty,
        error,
    )

    return {
        "Patch_Index": (
            patch_index
            if patch_index is not None
            else -1
        ),
        "Uncertainty_Type": uncertainty_name,
        "Pearson_Correlation": pearson_corr,
        "Pearson_P_Value": pearson_p,
        "Spearman_Correlation": spearman_corr,
        "Spearman_P_Value": spearman_p,
        "Number_of_Voxels": int(
            len(error)
        ),
    }


# =====================================================================
# 7. MAIN ANALYSIS
# =====================================================================

def main():

    print()
    print("=" * 72)
    print(
        "UNCERTAINTY–ERROR CORRELATION ANALYSIS"
    )
    print("=" * 72)

    print()
    print(
        f"Dataset Mode       : {DATASET_MODE}"
    )

    print(
        f"Device             : {DEVICE}"
    )

    print(
        f"Checkpoint         : {CHECKPOINT}"
    )

    print(
        f"MC-Dropout Samples : {MC_DROPOUT_SAMPLES}"
    )

    print(
        f"Attention          : {USE_ATTENTION}"
    )

    print(
        f"Residual           : {USE_RESIDUAL}"
    )

    print(
        f"Uncertainty        : {USE_UNCERTAINTY}"
    )

    # =================================================================
    # 8. REPRODUCIBILITY
    # =================================================================

    set_random_seed(
        UNCERTAINTY_ERROR_CORRELATION_SEED
    )

    # =================================================================
    # 9. VERIFY CHECKPOINT
    # =================================================================

    if not CHECKPOINT.is_file():

        raise FileNotFoundError(
            "Best model checkpoint was not found.\n\n"
            f"Expected checkpoint:\n{CHECKPOINT}\n\n"
            "Run the training stage and ensure that "
            "best_model.pth exists."
        )

    # =================================================================
    # 10. CREATE OUTPUT DIRECTORY
    # =================================================================

    OUTPUT_DIRECTORY.mkdir(
        parents=True,
        exist_ok=True,
    )

    # =================================================================
    # 11. BUILD DATASET
    # =================================================================

    dataset = build_dataset()

    if len(dataset) == 0:

        raise RuntimeError(
            "The reconstruction dataset contains no samples."
        )

    print()
    print(
        f"Dataset Length     : {len(dataset)}"
    )

    # Determine the number of patches to analyse.
    configured_patch_count = (
        UNCERTAINTY_ERROR_CORRELATION_NUM_PATCHES
    )

    if configured_patch_count is None:

        number_of_patches = len(dataset)

    else:

        if configured_patch_count <= 0:

            raise ValueError(
                "UNCERTAINTY_ERROR_CORRELATION_NUM_PATCHES "
                "must be greater than zero or None."
            )

        number_of_patches = min(
            configured_patch_count,
            len(dataset),
        )

    print(
        f"Patches Analysed   : {number_of_patches}"
    )

    # =================================================================
    # 12. CREATE MODEL
    # =================================================================

    model = Network3D(
        use_attention=USE_ATTENTION,
        use_residual=USE_RESIDUAL,
        use_uncertainty=USE_UNCERTAINTY,
    )

    # =================================================================
    # 13. CREATE PREDICTOR
    # =================================================================

    predictor = Predictor(
        model=model,
        checkpoint=str(CHECKPOINT),
        device=DEVICE,
        mc_samples=MC_DROPOUT_SAMPLES,
    )

    # =================================================================
    # 14. STORAGE
    # =================================================================

    # Overall missing-region error values.
    all_errors = []

    # Overall missing-region aleatoric uncertainty values.
    all_aleatoric = []

    # Overall missing-region epistemic uncertainty values.
    all_epistemic = []

    # Overall missing-region predictive uncertainty values.
    all_predictive = []

    # Patch-level results.
    patch_results = []

    # =================================================================
    # 15. PROCESS PATCHES
    # =================================================================

    print()
    print("-" * 72)
    print("PROCESSING PATCHES")
    print("-" * 72)

    for patch_index in range(
        number_of_patches
    ):

        print(
            f"Processing patch "
            f"{patch_index + 1}/{number_of_patches}"
        )

        # -------------------------------------------------------------
        # Retrieve dataset sample.
        # -------------------------------------------------------------

        sample = dataset[
            patch_index
        ]

        if len(sample) < 4:

            raise ValueError(
                "Dataset sample does not contain the expected "
                "minimum fields:\n"
                "(corrupted, target, mask, velocity)"
            )

        corrupted = sample[0]
        target = sample[1]
        mask = sample[2]
        velocity = sample[3]

        # -------------------------------------------------------------
        # Validate tensor types.
        # -------------------------------------------------------------

        if not torch.is_tensor(
            corrupted
        ):

            raise TypeError(
                "Corrupted seismic input must be a PyTorch tensor."
            )

        if not torch.is_tensor(
            target
        ):

            raise TypeError(
                "Target seismic data must be a PyTorch tensor."
            )

        if not torch.is_tensor(
            mask
        ):

            raise TypeError(
                "Observation mask must be a PyTorch tensor."
            )

        # -------------------------------------------------------------
        # Add batch dimension when required.
        # -------------------------------------------------------------

        if corrupted.ndim == 4:

            corrupted_input = (
                corrupted.unsqueeze(0)
            )

        elif corrupted.ndim == 5:

            corrupted_input = corrupted

        else:

            raise ValueError(
                "Unexpected corrupted input shape:\n"
                f"{tuple(corrupted.shape)}\n"
                "Expected [C,D,H,W] or [B,C,D,H,W]."
            )

        # -------------------------------------------------------------
        # Prepare target.
        # -------------------------------------------------------------

        if target.ndim == 4:

            target_tensor = (
                target.unsqueeze(0)
            )

        elif target.ndim == 5:

            target_tensor = target

        else:

            raise ValueError(
                "Unexpected target shape:\n"
                f"{tuple(target.shape)}\n"
                "Expected [C,D,H,W] or [B,C,D,H,W]."
            )

        # -------------------------------------------------------------
        # Prepare observation mask.
        # -------------------------------------------------------------

        if mask.ndim == 4:

            mask_tensor = (
                mask.unsqueeze(0)
            )

        elif mask.ndim == 5:

            mask_tensor = mask

        else:

            raise ValueError(
                "Unexpected mask shape:\n"
                f"{tuple(mask.shape)}\n"
                "Expected [C,D,H,W] or [B,C,D,H,W]."
            )

        # -------------------------------------------------------------
        # Validate mask values.
        # -------------------------------------------------------------

        unique_mask_values = torch.unique(
            mask_tensor.detach()
        )

        for value in unique_mask_values:

            value_float = float(
                value.item()
            )

            if (
                value_float != 0.0
                and
                value_float != 1.0
            ):

                raise ValueError(
                    "Observation mask contains values other "
                    "than 0 and 1.\n"
                    f"Unique values: "
                    f"{unique_mask_values.tolist()}"
                )

        # -------------------------------------------------------------
        # Validate input and target shape compatibility.
        # -------------------------------------------------------------

        if corrupted_input.shape != target_tensor.shape:

            raise ValueError(
                "Corrupted input and target shapes do not match.\n"
                f"Input : {tuple(corrupted_input.shape)}\n"
                f"Target: {tuple(target_tensor.shape)}"
            )

        if mask_tensor.shape != target_tensor.shape:

            raise ValueError(
                "Mask and target shapes do not match.\n"
                f"Mask  : {tuple(mask_tensor.shape)}\n"
                f"Target: {tuple(target_tensor.shape)}"
            )

        # -------------------------------------------------------------
        # Run predictive inference.
        #
        # The predictor performs the configured MC-Dropout inference
        # required for epistemic uncertainty estimation.
        # -------------------------------------------------------------

        (
            reconstruction,
            travel_time,
            aleatoric_std,
            epistemic_std,
        ) = predictor.predict(
            corrupted_input
        )

        # -------------------------------------------------------------
        # Validate reconstruction.
        # -------------------------------------------------------------

        if reconstruction.shape != target_tensor.shape:

            raise ValueError(
                "Reconstruction and target shapes do not match.\n"
                f"Reconstruction: "
                f"{tuple(reconstruction.shape)}\n"
                f"Target: "
                f"{tuple(target_tensor.shape)}"
            )

        # -------------------------------------------------------------
        # Validate uncertainty shapes.
        # -------------------------------------------------------------

        if aleatoric_std.shape != target_tensor.shape:

            raise ValueError(
                "Aleatoric uncertainty and target shapes do not match.\n"
                f"Aleatoric: "
                f"{tuple(aleatoric_std.shape)}\n"
                f"Target: "
                f"{tuple(target_tensor.shape)}"
            )

        if epistemic_std.shape != target_tensor.shape:

            raise ValueError(
                "Epistemic uncertainty and target shapes do not match.\n"
                f"Epistemic: "
                f"{tuple(epistemic_std.shape)}\n"
                f"Target: "
                f"{tuple(target_tensor.shape)}"
            )

        # -------------------------------------------------------------
        # Calculate predictive uncertainty.
        # -------------------------------------------------------------

        predictive_std = torch.sqrt(
            torch.clamp(
                aleatoric_std.pow(2)
                +
                epistemic_std.pow(2),
                min=0.0,
            )
        )

        # -------------------------------------------------------------
        # Calculate absolute reconstruction error.
        # -------------------------------------------------------------

        reconstruction_error = (
            reconstruction
            -
            target_tensor
        ).abs()

        # -------------------------------------------------------------
        # Missing-region selection.
        #
        # Mask convention:
        #
        #     1 = observed
        #     0 = missing
        #
        # Only missing voxels are included in the primary
        # uncertainty-error correlation.
        # -------------------------------------------------------------

        missing_mask = (
            mask_tensor == 0
        )

        missing_voxel_count = int(
            missing_mask.sum().item()
        )

        if missing_voxel_count < MIN_CORRELATION_SAMPLES:

            print(
                f"  WARNING: Patch {patch_index} contains only "
                f"{missing_voxel_count} missing voxel(s). "
                "Patch-level correlation will be undefined."
            )

            continue

        # -------------------------------------------------------------
        # Extract missing-region values.
        # -------------------------------------------------------------

        error_missing = (
            reconstruction_error[
                missing_mask
            ]
        )

        aleatoric_missing = (
            aleatoric_std[
                missing_mask
            ]
        )

        epistemic_missing = (
            epistemic_std[
                missing_mask
            ]
        )

        predictive_missing = (
            predictive_std[
                missing_mask
            ]
        )

        # -------------------------------------------------------------
        # Convert to NumPy.
        # -------------------------------------------------------------

        error_np = validate_array(
            error_missing.detach()
            .cpu()
            .numpy(),
            "Missing-region reconstruction error",
        )

        aleatoric_np = validate_array(
            aleatoric_missing.detach()
            .cpu()
            .numpy(),
            "Missing-region aleatoric uncertainty",
        )

        epistemic_np = validate_array(
            epistemic_missing.detach()
            .cpu()
            .numpy(),
            "Missing-region epistemic uncertainty",
        )

        predictive_np = validate_array(
            predictive_missing.detach()
            .cpu()
            .numpy(),
            "Missing-region predictive uncertainty",
        )

        # -------------------------------------------------------------
        # Store values for global missing-region analysis.
        # -------------------------------------------------------------

        all_errors.extend(
            error_np
        )

        all_aleatoric.extend(
            aleatoric_np
        )

        all_epistemic.extend(
            epistemic_np
        )

        all_predictive.extend(
            predictive_np
        )

        # -------------------------------------------------------------
        # Calculate patch-level correlations.
        # -------------------------------------------------------------

        uncertainty_components = {
            "Aleatoric": aleatoric_np,
            "Epistemic": epistemic_np,
            "Predictive": predictive_np,
        }

        for uncertainty_name, uncertainty_values in (
            uncertainty_components.items()
        ):

            record = correlation_record(
                uncertainty_name=uncertainty_name,
                uncertainty=uncertainty_values,
                error=error_np,
                patch_index=patch_index,
            )

            patch_results.append(
                record
            )

    # =================================================================
    # 16. VALIDATE GLOBAL DATA
    # =================================================================

    all_errors = validate_array(
        all_errors,
        "All missing-region reconstruction errors",
    )

    all_aleatoric = validate_array(
        all_aleatoric,
        "All missing-region aleatoric uncertainties",
    )

    all_epistemic = validate_array(
        all_epistemic,
        "All missing-region epistemic uncertainties",
    )

    all_predictive = validate_array(
        all_predictive,
        "All missing-region predictive uncertainties",
    )

    # Verify equal observation counts.
    observation_counts = {
        len(all_errors),
        len(all_aleatoric),
        len(all_epistemic),
        len(all_predictive),
    }

    if len(observation_counts) != 1:

        raise RuntimeError(
            "Uncertainty and error arrays do not contain "
            "the same number of observations."
        )

    # =================================================================
    # 17. GLOBAL CORRELATION ANALYSIS
    # =================================================================

    uncertainty_components = {
        "Aleatoric": all_aleatoric,
        "Epistemic": all_epistemic,
        "Predictive": all_predictive,
    }

    global_results = []

    for uncertainty_name, uncertainty_values in (
        uncertainty_components.items()
    ):

        (
            pearson_corr,
            pearson_p,
            spearman_corr,
            spearman_p,
        ) = calculate_correlations(
            uncertainty_values,
            all_errors,
        )

        global_results.append(
            {
                "Analysis_Region": "Missing_Voxels",
                "Uncertainty_Type": uncertainty_name,
                "Pearson_Correlation": pearson_corr,
                "Pearson_P_Value": pearson_p,
                "Spearman_Correlation": spearman_corr,
                "Spearman_P_Value": spearman_p,
                "Number_of_Voxels": len(
                    all_errors
                ),
                "Number_of_Patches": number_of_patches,
            }
        )

    results = pd.DataFrame(
        global_results
    )

    # =================================================================
    # 18. QUALITY-CONTROL CHECKS
    # =================================================================

    for column in [
        "Pearson_Correlation",
        "Spearman_Correlation",
    ]:

        for value in results[
            column
        ]:

            if np.isfinite(value):

                if not (
                    -1.0
                    <= value
                    <= 1.0
                ):

                    raise ValueError(
                        f"Invalid correlation coefficient "
                        f"detected: {value}"
                    )

    # =================================================================
    # 19. SAVE GLOBAL RESULTS
    # =================================================================

    results.to_csv(
        CSV_FILE,
        index=False,
    )

    # =================================================================
    # 20. SAVE PATCH-LEVEL RESULTS
    # =================================================================

    patch_results_df = pd.DataFrame(
        patch_results
    )

    patch_results_df.to_csv(
        PATCH_CSV_FILE,
        index=False,
    )

    # =================================================================
    # 21. DISPLAY RESULTS
    # =================================================================

    print()
    print("=" * 72)
    print(
        "GLOBAL MISSING-REGION CORRELATION RESULTS"
    )
    print("=" * 72)

    print()

    print(
        results.to_string(
            index=False
        )
    )

    print()
    print(
        f"Total missing voxels analysed: "
        f"{len(all_errors):,}"
    )

    print(
        f"Patches analysed: "
        f"{number_of_patches}"
    )

    print()
    print(
        "Saved global results:"
    )

    print(
        CSV_FILE
    )

    print()
    print(
        "Saved patch-level results:"
    )

    print(
        PATCH_CSV_FILE
    )

    print()
    print("=" * 72)
    print(
        "UNCERTAINTY–ERROR CORRELATION ANALYSIS COMPLETE"
    )
    print("=" * 72)
    print()


# =====================================================================
# 22. SCRIPT ENTRY POINT
# =====================================================================

if __name__ == "__main__":

    main()
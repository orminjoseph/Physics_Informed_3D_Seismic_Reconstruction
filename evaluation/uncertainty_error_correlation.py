"""
=====================================================================
Uncertainty–Error Correlation Analysis
=====================================================================

Purpose
-------
Quantifies the statistical relationship between voxel-wise
reconstruction error and predictive uncertainty for the seismic
reconstruction framework.

The predictive uncertainty is decomposed into:

    Predictive uncertainty
        =
    Aleatoric uncertainty
        +
    Epistemic uncertainty

The predictive standard deviation is computed as:

    sigma_predictive
        =
    sqrt(
        sigma_aleatoric^2
        +
        sigma_epistemic^2
    )

Analysis region
---------------
The primary analysis is performed on MISSING voxels only.

This is important because the reconstruction framework explicitly
preserves observed seismic data. Consequently, observed voxels may
have approximately zero reconstruction error after data-consistency
projection and should not dominate the uncertainty–error relationship.

Correlation methods
-------------------
1. Pearson correlation
   Measures linear association between reconstruction error and
   uncertainty.

2. Spearman correlation
   Measures monotonic association between reconstruction error and
   uncertainty.

Uncertainty components analysed
--------------------------------
    Aleatoric uncertainty
    Epistemic uncertainty
    Predictive uncertainty

Statistical caution
-------------------
Voxel-level observations within a seismic volume are spatially
correlated and therefore are not statistically independent.

Consequently, voxel-level p-values should be interpreted as
descriptive statistical evidence rather than as fully independent
hypothesis tests.

Patch-level correlation results are additionally reported to provide
a more conservative unit of analysis.

Travel-time predictions
-----------------------
Travel-time predictions are not used in this analysis.

Supported data modes
--------------------
    synthetic
    f3

Configuration
-------------
All dataset paths, model settings, uncertainty settings, device
settings, and analysis limits are obtained from utils/config.py.

Input
-----
The reconstruction dataset generated by build_dataset().

Outputs
-------
    REPORT_DIR/uncertainty_error_correlation/
        uncertainty_error_correlation.csv

        uncertainty_error_correlation_patch_level.csv

Author
------
    Ormin Joseph
=====================================================================
"""

